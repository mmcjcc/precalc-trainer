export type RefOp = '+' | '-' | '*' | '/'
export interface RefTerm {
  text: string
  exact?: boolean
}
export interface RefGroup {
  terms: RefTerm[]
  ops: RefOp[]
}
export type RefOperand = RefTerm | RefGroup

/** What one operand of a chain brings: its exact value and how far it can be trusted. */
interface Piece {
  value: Frac
  exact: boolean
  /** Meaningful only when !exact. */
  sigFigs: number
  place: number
  /** Figure count / place depends on whether you count before or after rounding (9.97 vs 10.0). */
  debatable: boolean
  /** A measured piece with no significant figure at all (a measured zero, or a group that rounds to zero). */
  degenerate: boolean
}

export interface RefChainResult {
  status: 'ok' | 'unsupported'
  reason?: string
  exactValue: Frac
  terminates: boolean
  rule: 'muldiv' | 'addsub'
  /** muldiv: fewest figures among the measured pieces. */
  limitSigFigs?: number
  /** addsub: least precise place among the measured pieces. */
  limitPlace?: number
  /** Indices (into the chain's pieces) that set the limit. */
  limiting: number[]
  rounding?: RefRounding
  debatable: boolean
}

function termPiece(t: RefTerm): Piece {
  const p = mustParse(t.text)
  return {
    value: p.value,
    exact: t.exact === true,
    sigFigs: p.sigFigs,
    place: p.lastPlace,
    debatable: false,
    degenerate: t.exact !== true && p.isZero,
  }
}

function familyOf(ops: readonly RefOp[]): 'muldiv' | 'addsub' | 'mixed' {
  const md = ops.filter((o) => o === '*' || o === '/').length
  if (md === ops.length) return 'muldiv'
  return md === 0 ? 'addsub' : 'mixed'
}

function fold(pieces: readonly Piece[], ops: readonly RefOp[]): Frac | null {
  let acc = pieces[0]!.value
  for (let k = 0; k < ops.length; k++) {
    const b = pieces[k + 1]!.value
    const op = ops[k]!
    if (op === '/' && fIsZero(b)) return null
    acc = op === '+' ? fAdd(acc, b) : op === '-' ? fSub(acc, b) : op === '*' ? fMul(acc, b) : fDiv(acc, b)
  }
  return acc
}

function chain(pieces: readonly Piece[], ops: readonly RefOp[]): RefChainResult {
  const fam = familyOf(ops)
  const base: RefChainResult = {
    status: 'unsupported',
    exactValue: frac(0n),
    terminates: true,
    rule: fam === 'addsub' ? 'addsub' : 'muldiv',
    limiting: [],
    debatable: pieces.some((p) => !p.exact && p.debatable),
  }
  if (fam === 'mixed') return { ...base, reason: 'ops of both families in one chain' }
  if (ops.length !== pieces.length - 1 || pieces.length < 2) return { ...base, reason: 'shape' }
  const v = fold(pieces, ops)
  if (v === null) return { ...base, reason: 'division by zero' }
  base.exactValue = v
  base.terminates = terminates(v)
  const measured = pieces.map((p, k) => ({ p, k })).filter((x) => !x.p.exact)
  if (measured.length === 0) return { ...base, reason: 'every number is exact' }
  if (measured.some((x) => x.p.degenerate)) return { ...base, reason: 'a measured piece has no significant figures' }
  if (fam === 'muldiv') {
    const nMin = measured.reduce((m, x) => Math.min(m, x.p.sigFigs), Infinity)
    const limiting = measured.filter((x) => x.p.sigFigs === nMin).map((x) => x.k)
    if (fIsZero(v)) return { ...base, reason: 'zero product' }
    return { ...base, status: 'ok', limitSigFigs: nMin, limiting, rounding: refRoundToSigFigs(v, nMin) }
  }
  const pMax = measured.reduce((m, x) => Math.max(m, x.p.place), -Infinity)
  const limiting = measured.filter((x) => x.p.place === pMax).map((x) => x.k)
  return { ...base, status: 'ok', limitPlace: pMax, limiting, rounding: refRoundToPlace(v, pMax) }
}

export function refChain(terms: readonly RefTerm[], ops: readonly RefOp[]): RefChainResult {
  return chain(terms.map(termPiece), ops)
}

export interface RefGroupInfo {
  operandIndex: number
  rule: 'muldiv' | 'addsub'
  exactValue: Frac
  sigFigs: number
  place: number
  debatable: boolean
}

export interface RefMixedResult extends RefChainResult {
  groups: RefGroupInfo[]
}

const isGroup = (o: RefOperand): o is RefGroup => (o as RefGroup).terms !== undefined

/**
 * One level of mixing. A group is evaluated exactly and carried forward with EVERY digit; what it
 * contributes to the outer rule is only "how far it can be trusted":
 *   + - group: its least precise place, and the figures its value shows down to that place;
 *   x / group: its fewest figures, and the place that many figures reach.
 * When counting on the un-rounded value and on the value rounded to that precision give different
 * answers (9.97 good to the tenths: 2 figures, or 10.0: 3 figures) the task is flagged debatable.
 */
export function refMixed(operands: readonly RefOperand[], ops: readonly RefOp[]): RefMixedResult {
  const groups: RefGroupInfo[] = []
  const pieces: Piece[] = []
  let unsupported: string | undefined
  operands.forEach((o, idx) => {
    if (!isGroup(o)) {
      pieces.push(termPiece(o))
      return
    }
    const inner = chain(o.terms.map(termPiece), o.ops)
    if (inner.status !== 'ok' || !inner.rounding) {
      if (inner.reason === 'every number is exact') {
        pieces.push({ value: inner.exactValue, exact: true, sigFigs: 0, place: 0, debatable: false, degenerate: false })
        return
      }
      unsupported = unsupported ?? `group ${idx}: ${inner.reason ?? 'unsupported'}`
      pieces.push({ value: inner.exactValue, exact: false, sigFigs: 0, place: 0, debatable: false, degenerate: true })
      return
    }
    const rounded = inner.rounding
    const v = inner.exactValue
    let sig: number
    let place: number
    let debatable: boolean
    let degenerate = false
    if (inner.rule === 'addsub') {
      place = inner.limitPlace!
      if (fIsZero(rounded.value) || fIsZero(v)) {
        degenerate = true
        sig = 0
        debatable = false
      } else {
        sig = firstPlace(rounded.value) - place + 1
        debatable = firstPlace(v) - place + 1 !== sig
      }
    } else {
      sig = inner.limitSigFigs!
      place = rounded.place
      debatable = rounded.carried
    }
    groups.push({ operandIndex: idx, rule: inner.rule, exactValue: v, sigFigs: sig, place, debatable })
    pieces.push({ value: v, exact: false, sigFigs: sig, place, debatable, degenerate })
  })
  const outer = chain(pieces, ops)
  if (unsupported !== undefined) return { ...outer, status: 'unsupported', reason: unsupported, groups }
  return { ...outer, groups }
}
