/**
 * Independent REFERENCE implementation of the significant-figure conventions, used only by
 * `sigfigs-differential.sweep.ts` to cross-check `src/engine/sigfigs`.
 *
 * It shares no code with the engine and works a different way on purpose:
 *   - every value is an exact fraction n/d over BigInt (never a float, never a digit string);
 *   - figures are counted ARITHMETICALLY, from two places (powers of ten):
 *       first significant place = floor(log10 |v|), found by comparing n with d x 10^k;
 *       last significant place  = power - (fraction digits typed)           when a point was typed,
 *                                 power + (10-adic valuation of the integer) when no point was typed;
 *       sigFigs = first - last + 1;
 *   - rounding is one integer division with remainder: tie exactly when 2r = divisor;
 *   - digits for displays are generated by long division.
 *
 * Conventions (the spec): nonzero digits count; captive zeros count; leading zeros never count;
 * trailing zeros count only with a decimal point; in scientific notation the rules apply to the
 * coefficient; exact numbers never limit; multiply/divide keeps the fewest figures; add/subtract
 * keeps the least precise place; mixed work carries every digit and rounds once; half-up on the
 * magnitude, with ties reported.
 */

// ---------------------------------------------------------------------------
// Exact fractions
// ---------------------------------------------------------------------------

export interface Frac {
  /** Numerator, carries the sign. */
  n: bigint
  /** Denominator, always > 0, gcd(n, d) = 1. */
  d: bigint
}

function absBig(a: bigint): bigint {
  return a < 0n ? -a : a
}

function gcd(a: bigint, b: bigint): bigint {
  let x = absBig(a)
  let y = absBig(b)
  while (y !== 0n) {
    const t = x % y
    x = y
    y = t
  }
  return x
}

export function pow10(k: number): bigint {
  if (k < 0) throw new Error('pow10 of a negative power')
  return 10n ** BigInt(k)
}

export function frac(n: bigint, d: bigint = 1n): Frac {
  if (d === 0n) throw new Error('zero denominator')
  if (d < 0n) {
    n = -n
    d = -d
  }
  const g = gcd(n, d)
  return g === 0n || g === 1n ? { n, d } : { n: n / g, d: d / g }
}

/** m x 10^p as a fraction. */
export function fracTimesPow10(m: bigint, p: number): Frac {
  return p >= 0 ? frac(m * pow10(p)) : frac(m, pow10(-p))
}

export const fAdd = (a: Frac, b: Frac): Frac => frac(a.n * b.d + b.n * a.d, a.d * b.d)
export const fSub = (a: Frac, b: Frac): Frac => frac(a.n * b.d - b.n * a.d, a.d * b.d)
export const fMul = (a: Frac, b: Frac): Frac => frac(a.n * b.n, a.d * b.d)
export function fDiv(a: Frac, b: Frac): Frac {
  if (b.n === 0n) throw new Error('division by zero')
  return frac(a.n * b.d, a.d * b.n)
}
export const fEq = (a: Frac, b: Frac): boolean => a.n === b.n && a.d === b.d
export const fIsZero = (a: Frac): boolean => a.n === 0n
export const fAbs = (a: Frac): Frac => ({ n: absBig(a.n), d: a.d })
export const fNeg = (a: Frac): Frac => ({ n: -a.n, d: a.d })

/** floor(log10 |v|): the place of the first significant digit. v must not be zero. */
export function firstPlace(v: Frac): number {
  if (v.n === 0n) throw new Error('zero has no first significant place')
  const n = absBig(v.n)
  const d = v.d
  // ge(k): |v| >= 10^k
  const ge = (k: number): boolean => (k >= 0 ? n >= d * pow10(k) : n * pow10(-k) >= d)
  let k = n.toString().length - d.toString().length
  while (!ge(k)) k--
  while (ge(k + 1)) k++
  return k
}

/** Does the decimal expansion stop? (denominator has no prime factor other than 2 and 5) */
export function terminates(v: Frac): boolean {
  let d = v.d
  while (d % 2n === 0n) d /= 2n
  while (d % 5n === 0n) d /= 5n
  return d === 1n
}

/**
 * Decimal expansion by long division: the integer part, then `fractionDigits` digits produced one
 * remainder at a time. Truncated, never rounded. `exact` says whether nothing was cut off.
 */
export function longDivision(v: Frac, fractionDigits: number): { text: string; exact: boolean } {
  const neg = v.n < 0n
  const n = absBig(v.n)
  let out = (n / v.d).toString()
  let r = n % v.d
  let frac = ''
  for (let i = 0; i < fractionDigits && r !== 0n; i++) {
    r *= 10n
    frac += (r / v.d).toString()
    r %= v.d
  }
  if (frac.length > 0) out += '.' + frac
  return { text: (neg && v.n !== 0n ? '-' : '') + out, exact: r === 0n }
}

/** Minimal plain decimal of a terminating value: "0.0045", "1200", "-3", "0". */
export function plainDecimal(v: Frac): string {
  if (!terminates(v)) throw new Error('plainDecimal of a repeating value')
  const r = longDivision(v, 4000)
  if (!r.exact) throw new Error('expansion too long')
  return r.text
}

// ---------------------------------------------------------------------------
// Reading a numeral
// ---------------------------------------------------------------------------

export interface RefDigit {
  /** Index into the text handed to refParse. */
  index: number
  digit: number
  /** Power of ten this digit stands for (power-of-ten part included). */
  place: number
  significant: boolean
}

export interface RefNumeral {
  ok: true
  value: Frac
  negative: boolean
  isZero: boolean
  sigFigs: number
  /** For zero: same as lastPlace. */
  firstPlace: number
  /** For zero: the place of the last written digit. */
  lastPlace: number
  /** Place of the last WRITTEN coefficient digit, significant or not. */
  lastWrittenPlace: number
  hasPoint: boolean
  scientific: boolean
  /** Scientific with exactly one nonzero digit in front of the point. */
  normalized: boolean
  exponent: number
  digits: RefDigit[]
}

export interface RefParseFailure {
  ok: false
  /** Where the reading stopped (index into the text handed in). */
  position: number
}

const MINUS = '-−'
const isDigit = (c: string | undefined): boolean => c !== undefined && c >= '0' && c <= '9'

/**
 * Grammar (the spec'd student input, nothing more):
 *   [sign] ( digits [ "." [digits] ] | "." digits ) [ power ]
 *   power = ("e" | "E") [sign] digits  |  ("x" | "X" | "×" | "*") "10" "^" [sign] digits     (spaces allowed around
 *           the multiplication sign and the caret)
 * The value is accumulated as integers; nothing is sliced or re-joined.
 */
export function refParse(raw: string): RefNumeral | RefParseFailure {
  let i = 0
  const n = raw.length
  const skipSpaces = (): void => {
    while (i < n && (raw[i] === ' ' || raw[i] === '\t')) i++
  }
  skipSpaces()
  let negative = false
  if (i < n && (raw[i] === '+' || MINUS.includes(raw[i]!))) {
    negative = raw[i] !== '+'
    i++
  }
  let mantissa = 0n
  let digitCount = 0
  let fractionDigits = 0
  let hasPoint = false
  let integerDigits = 0
  const seen: { index: number; digit: number; afterPoint: number }[] = []
  while (i < n) {
    const c = raw[i]!
    if (isDigit(c)) {
      const dv = c.charCodeAt(0) - 48
      mantissa = mantissa * 10n + BigInt(dv)
      digitCount++
      if (hasPoint) fractionDigits++
      else integerDigits++
      seen.push({ index: i, digit: dv, afterPoint: hasPoint ? fractionDigits : 0 })
      i++
    } else if (c === '.' && !hasPoint) {
      hasPoint = true
      i++
    } else break
  }
  if (digitCount === 0) return { ok: false, position: i }

  // optional power of ten
  let exponent = 0
  let scientific = false
  const save = i
  skipSpaces()
  if (i < n) {
    const c = raw[i]!
    let sawPower = false
    if (c === 'e' || c === 'E') {
      i++
      sawPower = true
    } else if (c === 'x' || c === 'X' || c === '×' || c === '*') {
      i++
      skipSpaces()
      if (raw[i] !== '1' || raw[i + 1] !== '0') return { ok: false, position: i }
      i += 2
      skipSpaces()
      if (raw[i] !== '^') return { ok: false, position: i }
      i++
      skipSpaces()
      sawPower = true
    }
    if (sawPower) {
      let eneg = false
      if (i < n && (raw[i] === '+' || MINUS.includes(raw[i]!))) {
        eneg = raw[i] !== '+'
        i++
      }
      if (!isDigit(raw[i])) return { ok: false, position: i }
      let e = 0
      while (isDigit(raw[i])) {
        e = e * 10 + (raw[i]!.charCodeAt(0) - 48)
        if (e > 100000) return { ok: false, position: i }
        i++
      }
      exponent = eneg ? -e : e
      scientific = true
    } else {
      i = save
    }
  }
  skipSpaces()
  if (i < n) return { ok: false, position: i }

  const shift = exponent - fractionDigits // place of the last WRITTEN digit
  const magnitude = fracTimesPow10(mantissa, shift)
  const value = negative ? fNeg(magnitude) : magnitude
  const isZero = mantissa === 0n

  let first: number
  let last: number
  if (isZero) {
    first = shift
    last = shift
  } else {
    first = firstPlace(magnitude)
    if (hasPoint) last = shift
    else {
      let v10 = 0
      let m = mantissa
      while (m % 10n === 0n) {
        m /= 10n
        v10++
      }
      last = shift + v10
    }
  }
  const digits: RefDigit[] = seen.map((s, k) => {
    // k-th written digit of digitCount stands for 10^(shift + digitCount - 1 - k)
    const place = shift + (digitCount - 1 - k)
    return { index: s.index, digit: s.digit, place, significant: !isZero && place <= first && place >= last }
  })
  const normalized = scientific && integerDigits === 1 && seen[0]!.digit !== 0
  return {
    ok: true,
    value,
    negative,
    isZero,
    sigFigs: isZero ? 0 : first - last + 1,
    firstPlace: first,
    lastPlace: last,
    lastWrittenPlace: shift,
    hasPoint,
    scientific,
    normalized,
    exponent,
    digits,
  }
}

export function mustParse(text: string): RefNumeral {
  const p = refParse(text)
  if (!p.ok) throw new Error(`reference cannot read "${text}" (stopped at ${p.position})`)
  return p
}

// ---------------------------------------------------------------------------
// Rounding
// ---------------------------------------------------------------------------

export interface RefRounding {
  value: Frac
  /** Place of the last kept digit (after any carry into a new digit, for figure rounding). */
  place: number
  /** Figures the rounded value shows down to `place`; 0 when it rounded to zero. */
  sigFigs: number
  tie: boolean
  direction: 'up' | 'down' | 'exact'
  firstDropped: number
  truncated: Frac
  /** Place the truncation was made at (no carry can happen when chopping). */
  truncatedPlace: number
  /** Rounding carried into a new leading digit (9.97 -> 10.0). */
  carried: boolean
}

/** Half-up on the magnitude at 10^place, by one integer division with remainder. */
export function refRoundToPlace(v: Frac, place: number): RefRounding {
  const neg = v.n < 0n
  const num = place >= 0 ? absBig(v.n) : absBig(v.n) * pow10(-place)
  const den = place >= 0 ? v.d * pow10(place) : v.d
  const q = num / den
  const r = num % den
  const tie = 2n * r === den
  const up = 2n * r >= den
  const kept = up ? q + 1n : q
  const mk = (m: bigint): Frac => fracTimesPow10(neg ? -m : m, place)
  const value = mk(kept)
  const carried = kept !== 0n && q !== 0n && kept.toString().length !== q.toString().length
  return {
    value,
    place,
    sigFigs: kept === 0n ? 0 : kept.toString().length,
    tie,
    direction: r === 0n ? 'exact' : up ? 'up' : 'down',
    firstDropped: Number((r * 10n) / den),
    truncated: mk(q),
    truncatedPlace: place,
    carried,
  }
}

/** To n significant figures. A carry into a new digit (0.99961 -> 1.00) moves the place up by one. */
export function refRoundToSigFigs(v: Frac, n: number): RefRounding {
  if (fIsZero(v)) throw new Error('cannot round zero to significant figures')
  if (n < 1) throw new Error('need at least one figure')
  const p0 = firstPlace(v)
  const r = refRoundToPlace(v, p0 - n + 1)
  const carried = firstPlace(r.value) !== p0
  return { ...r, place: carried ? r.place + 1 : r.place, sigFigs: n, carried }
}

