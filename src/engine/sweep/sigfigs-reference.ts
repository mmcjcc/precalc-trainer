// Writing a value so that it SHOWS its last significant place
// ---------------------------------------------------------------------------

export type RefPowerStyle = 'e' | 'E' | 'x10^' | ' x 10^' | '×10^' | ' × 10^' | '*10^' | ' * 10^'

/** Scientific spelling: value is a multiple of 10^place and not zero. */
export function refScientific(v: Frac, place: number, style: RefPowerStyle = 'e', unicodeMinus = false): string {
  if (fIsZero(v)) throw new Error('zero has no scientific form')
  const m = fDiv(fAbs(v), fracTimesPow10(1n, place))
  if (m.d !== 1n) throw new Error('value is not a multiple of 10^place')
  const s = m.n.toString()
  const power = place + s.length - 1
  const minus = unicodeMinus ? '−' : '-'
  const coeff = s.length === 1 ? s : s[0] + '.' + s.slice(1)
  return (v.n < 0n ? minus : '') + coeff + style + (power < 0 ? minus + String(-power) : String(power))
}

/**
 * Standard spelling, or null when plain digits cannot show that place: 2000 good to the hundreds has
 * no standard spelling (its zeros would read as placeholders), 12000 good to the thousands does.
 */
export function refStandard(v: Frac, place: number): string | null {
  const m = fDiv(fAbs(v), fracTimesPow10(1n, place))
  if (m.d !== 1n) throw new Error('value is not a multiple of 10^place')
  let s = m.n.toString()
  const sign = v.n < 0n ? '-' : ''
  if (place > 0) return m.n % 10n === 0n ? null : sign + s + '0'.repeat(place)
  if (place === 0) return sign + s + (s.endsWith('0') && s !== '0' ? '.' : '')
  const f = -place
  while (s.length <= f) s = '0' + s
  return sign + s.slice(0, s.length - f) + '.' + s.slice(s.length - f)
}

